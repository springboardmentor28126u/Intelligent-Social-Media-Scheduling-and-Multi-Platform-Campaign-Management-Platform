from app.services.publishing_service import publishing_service


class OAuthService:

    def get_authorization_url(
        self,
        platform: str,
        state: str,
        social_account=None,
    ):
        integration = publishing_service.get_platform_integration(
            platform,
            social_account=social_account,
        )

        return integration.get_authorization_url(
            state=state
        )

    def exchange_code_for_token(
        self,
        platform: str,
        code: str,
        state: str | None = None,
        social_account=None,
    ):
        integration = publishing_service.get_platform_integration(
            platform,
            social_account=social_account,
        )

        platform_name = platform.lower().strip()

        # =====================================
        # X / Twitter
        # =====================================
        #
        # X requires state because our Twitter
        # integration uses it for PKCE.
        #
        if platform_name in ("twitter", "x"):
            return integration.exchange_code_for_token(
                code=code,
                state=state,
            )

        # =====================================
        # YouTube
        # =====================================
        #
        # YouTube OAuth also receives the state
        # generated by SocialPilot.
        #
        if platform_name == "youtube":
            return integration.exchange_code_for_token(
                code=code,
                state=state,
            )

        # =====================================
        # Other Platforms
        # =====================================

        return integration.exchange_code_for_token(
            code
        )


oauth_service = OAuthService()