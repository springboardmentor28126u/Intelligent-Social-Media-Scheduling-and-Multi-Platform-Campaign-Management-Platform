// Builds campaign PDF reports directly with jsPDF (no html2canvas needed).
import jsPDF from "jspdf";
import type { Campaign, CampaignStats } from "@/hooks/useCampaigns";

const API_BASE_URL = "http://localhost:8000";

// Shape of GET /analytics/campaigns/{id} (only fields seen in Swagger)
interface PlatformRow {
  platform: string;
  likes: number;
  shares: number;
  comments: number;
  reach: number;
  impressions: number;
  clicks: number;
  engagement_rate: number;
  ctr: number;
}
interface CampaignDetail {
  campaign_id: string;
  name: string;
  status: string;
  posts: number;
  totals: {
    likes: number;
    shares: number;
    comments: number;
    reach: number;
    impressions: number;
    clicks: number;
    engagement_rate: number;
    ctr: number;
    budget: number;
    cost_per_click: number;
    estimated_revenue: number;
    roi_percent: number;
  };
  by_platform: PlatformRow[];
}

/* ---------- Layout constants (A4, mm) ---------- */
const PAGE_H = 297;
const PAGE_W = 210;
const MARGIN = 14;
const CONTENT_W = PAGE_W - MARGIN * 2; // 182

type Ctx = { pdf: jsPDF; y: number };

/* ---------- Small helpers ---------- */
// Built-in PDF fonts cannot draw the rupee symbol, so we write "Rs."
const inr = (n: number) => `Rs. ${Math.round(n).toLocaleString("en-IN")}`;
const num = (n: number | undefined) => (n ?? 0).toLocaleString("en-IN");
const statusLabel = (s: string) =>
  s === "paused" ? "Draft" : s.charAt(0).toUpperCase() + s.slice(1);
const platformName = (p: string) =>
  p === "twitter" ? "X (Twitter)" : p.charAt(0).toUpperCase() + p.slice(1);
const cut = (t: string, max: number) => (t.length > max ? t.slice(0, max - 3) + "..." : t);
const today = () => new Date().toISOString().split("T")[0];
const slug = (t: string) =>
  t.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "campaign";

// Start a new page if the next block would not fit
function ensure(ctx: Ctx, h: number) {
  if (ctx.y + h > PAGE_H - 15) {
    ctx.pdf.addPage();
    ctx.y = 20;
  }
}

// Coloured title band at the top of page 1
function banner(ctx: Ctx, kicker: string, title: string, sub: string) {
  const { pdf } = ctx;
  pdf.setFillColor(79, 70, 229);
  pdf.rect(0, 0, PAGE_W, 38, "F");
  pdf.setTextColor(199, 210, 254);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(9);
  pdf.text(kicker, MARGIN, 14);
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(20);
  pdf.text(cut(title, 45), MARGIN, 25);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(9);
  pdf.text(sub, MARGIN, 32);
  ctx.y = 52;
}

function heading(ctx: Ctx, text: string) {
  ensure(ctx, 20);
  ctx.pdf.setFont("helvetica", "bold");
  ctx.pdf.setFontSize(13);
  ctx.pdf.setTextColor(17, 24, 39);
  ctx.pdf.text(text, MARGIN, ctx.y);
  ctx.y += 8;
}

// "Label ........ value" line (value wraps if long)
function kv(ctx: Ctx, label: string, value: string) {
  const { pdf } = ctx;
  const lines: string[] = pdf.splitTextToSize(value || "-", 125);
  ensure(ctx, lines.length * 5 + 2);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(10);
  pdf.setTextColor(107, 114, 128);
  pdf.text(label, MARGIN, ctx.y);
  pdf.setTextColor(17, 24, 39);
  pdf.text(lines, MARGIN + 45, ctx.y);
  ctx.y += lines.length * 5 + 1.5;
}

// Simple table: first column left-aligned, the rest right-aligned
function table(ctx: Ctx, headers: string[], rows: string[][], widths: number[]) {
  const { pdf } = ctx;

  const drawHeader = () => {
    pdf.setFillColor(243, 244, 246);
    pdf.rect(MARGIN, ctx.y - 5, CONTENT_W, 8, "F");
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(9);
    pdf.setTextColor(55, 65, 81);
    let x = MARGIN;
    headers.forEach((h, i) => {
      if (i === 0) pdf.text(h, x + 2, ctx.y);
      else pdf.text(h, x + widths[i] - 2, ctx.y, { align: "right" });
      x += widths[i];
    });
    ctx.y += 8;
  };

  ensure(ctx, 25);
  drawHeader();

  rows.forEach((row) => {
    if (ctx.y > PAGE_H - 20) {
      pdf.addPage();
      ctx.y = 20;
      drawHeader();
    }
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    pdf.setTextColor(17, 24, 39);
    let x = MARGIN;
    row.forEach((cell, i) => {
      if (i === 0) pdf.text(cell, x + 2, ctx.y);
      else pdf.text(cell, x + widths[i] - 2, ctx.y, { align: "right" });
      x += widths[i];
    });
    pdf.setDrawColor(229, 231, 235);
    pdf.line(MARGIN, ctx.y + 2.5, MARGIN + CONTENT_W, ctx.y + 2.5);
    ctx.y += 7;
  });
  ctx.y += 4;
}

// "Page X of Y" + brand line on every page
function addFooters(pdf: jsPDF) {
  const total = pdf.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    pdf.setPage(i);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.setTextColor(156, 163, 175);
    pdf.text("Generated by SocialPilot", MARGIN, PAGE_H - 8);
    pdf.text(`Page ${i} of ${total}`, PAGE_W - MARGIN, PAGE_H - 8, { align: "right" });
  }
}

// Backend stores one "objectives" text: "<objective>\n\n<description>"
function splitObjectives(text: string | null) {
  if (!text) return { objective: "", description: "" };
  const i = text.indexOf("\n\n");
  return i === -1
    ? { objective: text, description: "" }
    : { objective: text.slice(0, i), description: text.slice(i + 2) };
}

/* =====================================================
   REPORT 1: one campaign (fetches its detailed analytics)
===================================================== */
export async function downloadCampaignReport(c: Campaign, token: string) {
  const res = await fetch(`${API_BASE_URL}/analytics/campaigns/${c.id}`, {
    headers: { Authorization: `Bearer ${token}` },
  });
  if (!res.ok) throw new Error("Could not load campaign analytics.");
  const d: CampaignDetail = await res.json();
  const t = d.totals;

  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const ctx: Ctx = { pdf, y: 0 };
  const { objective, description } = splitObjectives(c.objectives);

  banner(ctx, "SOCIALPILOT  |  CAMPAIGN REPORT", c.name, `Generated ${new Date().toLocaleString()}`);

  heading(ctx, "Campaign Details");
  kv(ctx, "Status", statusLabel(c.status));
  kv(ctx, "Period", `${c.start_date.slice(0, 10)} to ${c.end_date.slice(0, 10)}`);
  kv(ctx, "Platforms", c.platforms.map(platformName).join(", "));
  kv(ctx, "Objective", objective);
  if (description) kv(ctx, "Description", description);
  kv(ctx, "Posts", String(d.posts));
  ctx.y += 4;

  heading(ctx, "Performance Summary");
  table(
    ctx,
    ["Metric", "Value"],
    [
      ["Reach", num(t.reach)],
      ["Impressions", num(t.impressions)],
      ["Likes", num(t.likes)],
      ["Shares", num(t.shares)],
      ["Comments", num(t.comments)],
      ["Clicks", num(t.clicks)],
      ["Engagement rate", `${t.engagement_rate}%`],
      ["Click-through rate (CTR)", `${t.ctr}%`],
    ],
    [132, 50]
  );

  heading(ctx, "Budget and ROI");
  table(
    ctx,
    ["Metric", "Value"],
    [
      ["Budget", inr(t.budget)],
      ["Cost per click", inr(t.cost_per_click)],
      ["Estimated revenue", inr(t.estimated_revenue)],
      ["ROI", `${t.roi_percent}%`],
    ],
    [132, 50]
  );

  if (d.by_platform?.length) {
    heading(ctx, "Platform Breakdown");
    table(
      ctx,
      ["Platform", "Reach", "Likes", "Shares", "Comments", "Clicks", "Eng. %"],
      d.by_platform.map((p) => [
        platformName(p.platform),
        num(p.reach),
        num(p.likes),
        num(p.shares),
        num(p.comments),
        num(p.clicks),
        `${p.engagement_rate ?? 0}%`,
      ]),
      [42, 24, 24, 24, 26, 22, 20]
    );
  }

  addFooters(pdf);
  pdf.save(`socialpilot-campaign-${slug(c.name)}-${today()}.pdf`);
}

/* =====================================================
   REPORT 2: all campaigns summary (uses data already loaded)
===================================================== */
export function downloadAllCampaignsReport(
  campaigns: Campaign[],
  stats: Record<string, CampaignStats>
) {
  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  const ctx: Ctx = { pdf, y: 0 };

  const all = campaigns.map((c) => stats[c.id]).filter(Boolean);
  const totalBudget = campaigns.reduce((s, c) => s + c.budget, 0);
  const totalRevenue = all.reduce((s, x) => s + x.estimated_revenue, 0);
  const totalReach = all.reduce((s, x) => s + x.reach, 0);
  const totalClicks = all.reduce((s, x) => s + x.clicks, 0);
  // Overall ROI across all campaigns
  const overallRoi = totalBudget > 0 ? ((totalRevenue - totalBudget) / totalBudget) * 100 : 0;

  banner(
    ctx,
    "SOCIALPILOT  |  CAMPAIGNS SUMMARY",
    "All Campaigns Report",
    `Generated ${new Date().toLocaleString()}`
  );

  heading(ctx, "Overview");
  kv(ctx, "Total campaigns", String(campaigns.length));
  kv(ctx, "Total budget", inr(totalBudget));
  kv(ctx, "Total reach", num(totalReach));
  kv(ctx, "Total clicks", num(totalClicks));
  kv(ctx, "Estimated revenue", inr(totalRevenue));
  kv(ctx, "Overall ROI", `${overallRoi.toFixed(1)}%`);
  ctx.y += 4;

  heading(ctx, "Campaign Performance");
  table(
    ctx,
    ["Campaign", "Status", "Budget", "Reach", "Clicks", "ROI"],
    campaigns.map((c) => {
      const s = stats[c.id];
      return [
        cut(c.name, 26),
        statusLabel(c.status),
        inr(c.budget),
        s ? num(s.reach) : "-",
        s ? num(s.clicks) : "-",
        s ? `${s.roi_percent}%` : "-",
      ];
    }),
    [58, 24, 32, 26, 22, 20]
  );

  addFooters(pdf);
  pdf.save(`socialpilot-all-campaigns-${today()}.pdf`);
}